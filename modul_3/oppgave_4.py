poeng = 0
# Jeg tror poeng blir: 10
poeng += 10
print(poeng)
poeng += 25
# Jeg tror poeng blir. 35
print(poeng)
poeng -= 5
# Jeg tror poeng blir 30
print(poeng)
poeng *= 2
# Jeg tror poeng blir 60
print(poeng)
poeng /= 4
# Jeg tror poeng blir 15.0
print(poeng)
poeng = poeng + 10
print(poeng)
# --- Refleksjon ---
# Alle forutsigelsene mine stemte.
# Datatypen ble til flaot på siste steget fordi jeg delte på 4.
# Ja, utvidelsen ga samme resultat som +=. 
# += er en kortere, raskere og en ryddigere måte å skrive på.
